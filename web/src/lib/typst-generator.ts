import { getSocialLabel, type SignatureData } from "./types";
import {
  displayUrl,
  normalizePhone,
  normalizeUrl,
  resolveSocialUrl,
} from "./links";

/**
 * Escape user text for Typst markup. Every character that can start markup syntax is backslash-escaped,
 * including comments (`//`, `/*`), raw text, smart quotes, non-breaking spaces, and list or heading markers.
 */
export function escapeTypst(str: string): string {
  return str.replace(/[\\/*_`$#@<>[\]~\-+=."':]/g, "\\$&");
}

/** Escape a value placed inside a Typst string literal, where only `\` and `"` are special. */
export function escapeTypstString(str: string): string {
  return str.replace(/[\\"]/g, "\\$&");
}

function hexToTypstRgb(hex: string): string {
  return `rgb("${escapeTypstString(hex)}")`;
}

export function generateTypstCode(data: SignatureData): string {
  const {
    name,
    pronouns,
    subtitleText,
    subtitleOrganization,
    subtitleUrl,
    titles,
    email,
    phone,
    website,
    socialLinks,
    colors,
    fonts,
    layout,
  } = data;
  const hasImage = !!(data.profileImageUrl || data.profileImage);
  const hasContact = !!(email || phone || website);
  const hasTitles = titles.some((t) => t.title || t.organization);
  const hasHeader = !!(name || subtitleText || subtitleOrganization);

  const link = (href: string, content: string) =>
    href
      ? `#text(fill: ${hexToTypstRgb(colors.linkColor)})[#link("${escapeTypstString(href)}")[${content}]]`
      : content;

  // Map font family to a Typst-compatible font name
  const fontName = fonts.fontFamily.split(",")[0].replace(/['"]/g, "").trim();

  // Typst cannot load remote or embedded images, so the photo is always read from a local file.
  let imageComment = "";
  if (hasImage) {
    imageComment =
      '// NOTE: Save your profile image as "photo.jpg" next to this file before compiling.\n';
    if (data.profileImageUrl) {
      imageComment += `// Source: ${data.profileImageUrl.replace(/[\r\n]/g, " ")}\n`;
    }
  }

  const borderRadius =
    layout.imageShape === "circle"
      ? "50%"
      : layout.imageShape === "rounded"
        ? "4pt"
        : "0pt";

  let code = `// Email Signature - Generated by EmailSmith
#set page(width: 500pt, height: auto, margin: 8pt)
#set text(font: "${escapeTypstString(fontName)}", size: ${fonts.textSize}pt, fill: ${hexToTypstRgb(colors.textColor)})
${imageComment}
`;

  // Signoff
  if (layout.showSignoff && layout.signoffText) {
    code += `#text(size: ${fonts.textSize}pt)[${escapeTypst(layout.signoffText)}]\n#v(8pt)\n\n`;
  }

  const divider = () => {
    if (layout.dividerStyle === "none") return "#v(4pt)\n";
    const paint = hexToTypstRgb(colors.dividerColor);
    const stroke =
      layout.dividerStyle === "solid"
        ? `0.5pt + ${paint}`
        : `(dash: "${layout.dividerStyle}", paint: ${paint}, thickness: 0.5pt)`;
    return `#v(4pt)\n#line(length: 100%, stroke: ${stroke})\n#v(4pt)\n`;
  };

  // Build the info content
  let infoContent = "";

  // Name
  if (name) {
    infoContent += `#text(size: ${fonts.nameSize}pt, weight: "bold", fill: ${hexToTypstRgb(colors.nameColor)})[${escapeTypst(name)}]`;
    if (pronouns) {
      infoContent += ` #text(size: ${fonts.textSize}pt, fill: ${hexToTypstRgb(colors.textColor)})[(${escapeTypst(pronouns)})]`;
    }
    infoContent += "\n";
  }

  // Subtitle
  if (subtitleText || subtitleOrganization) {
    let parts = "";
    if (subtitleText) {
      parts += escapeTypst(subtitleText);
    }
    if (subtitleOrganization) {
      if (parts) parts += ", ";
      parts += `*${link(normalizeUrl(subtitleUrl), escapeTypst(subtitleOrganization))}*`;
    }
    infoContent += `#text(size: ${fonts.subtitleSize}pt, fill: ${hexToTypstRgb(colors.titleColor)})[${parts}]\n`;
  }

  // Dividers separate the header, titles, and contact groups wherever two are adjacent, matching the HTML output.
  if (hasHeader && (hasTitles || hasContact)) {
    infoContent += divider();
  }

  // Titles
  const filteredTitles = titles.filter((t) => t.title || t.organization);
  for (const t of filteredTitles) {
    const titlePart = t.title ? `*${escapeTypst(t.title)}*` : "";
    const orgPart = t.organization
      ? link(normalizeUrl(t.url), escapeTypst(t.organization))
      : "";
    const combined =
      titlePart && orgPart ? `${titlePart}, ${orgPart}` : titlePart || orgPart;
    infoContent += `#text(size: ${fonts.titleSize}pt, fill: ${hexToTypstRgb(colors.titleColor)})[${combined}]\n`;
  }

  if (hasTitles && hasContact) {
    infoContent += divider();
  }

  // Contact info
  const contactParts: string[] = [];
  if (phone) {
    const dial = normalizePhone(phone);
    contactParts.push(link(dial && `tel:${dial}`, escapeTypst(phone)));
  }
  if (email) {
    contactParts.push(link(`mailto:${email.trim()}`, escapeTypst(email)));
  }
  if (website) {
    contactParts.push(
      link(normalizeUrl(website), escapeTypst(displayUrl(website))),
    );
  }
  if (contactParts.length > 0) {
    infoContent += `#text(size: ${fonts.textSize}pt)[${contactParts.join(" | ")}]\n`;
  }

  // Social links (as text links in Typst - icons would require image files)
  const socialParts = socialLinks
    .map((s) => ({ s, href: resolveSocialUrl(s.platform, s.url) }))
    .filter(({ href }) => href)
    .map(({ s, href }) => link(href, escapeTypst(getSocialLabel(s.platform))));
  if (socialParts.length > 0) {
    infoContent += `#v(2pt)\n#text(size: ${fonts.textSize}pt)[${socialParts.join(" #h(6pt) ")}]\n`;
  }

  // CTA / action link
  const ctaHref = normalizeUrl(data.ctaUrl);
  if (data.ctaText && ctaHref) {
    infoContent += `#v(4pt)\n#text(size: ${fonts.textSize}pt, weight: "bold", fill: ${hexToTypstRgb(colors.accentColor)})[#link("${escapeTypstString(ctaHref)}")[${escapeTypst(data.ctaText)}]]\n`;
  }

  const photo = `box(
  clip: true,
  radius: ${borderRadius},
  width: ${layout.imageSize}pt,
  height: ${layout.imageSize}pt,
  image("photo.jpg", width: ${layout.imageSize}pt, height: ${layout.imageSize}pt, fit: "cover")
)`;

  // Wrap in layout
  if (layout.layout === "horizontal" && hasImage) {
    code += `#grid(
  columns: (${layout.imageSize}pt, 1fr),
  column-gutter: 16pt,
  ${photo.replace(/\n/g, "\n  ")},
  [
${infoContent
  .split("\n")
  .map((l) => "    " + l)
  .join("\n")}
  ]
)\n`;
  } else if (layout.layout === "stacked" && hasImage) {
    code += `#${photo}
#v(8pt)
${infoContent}`;
  } else {
    code += infoContent;
  }

  return code;
}
